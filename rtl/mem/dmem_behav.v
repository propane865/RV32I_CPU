// Data memory - behavioural model (simulation only)
//
// 4 KiB of byte-addressable storage with a synchronous write port and a
// combinational read port, which is what the pipeline expects: the address is
// presented in MEM, and the read data is captured into MEM/WB on the same edge.
//
// The testbench reads IMPL.mem directly to check store results.
//
// Sub-word accesses are taken from addr[11:0] with the bytes read upwards, i.e.
// addr[1:0] is ignored beyond selecting the containing byte. That is not what
// rtl/mem/dmem_sram.v does - see the note in rtl/mem/dmem.v.
module dmem_behav(input clk, w_ena, is_signed, input [1:0] width, input [31:0] addr, w_data, output reg [31:0] r_data);
    `include "defines.vh"

    reg [7:0] mem [0:4095];

    wire [11:0] base = addr[11:0];

    always @(posedge clk) begin
        if (w_ena) begin
            case (width)
                `MEM_B: mem[base] <= w_data[7:0];
                `MEM_H: begin
                    mem[base]   <= w_data[7:0];
                    mem[base+1] <= w_data[15:8];
                end
                `MEM_W: begin
                    mem[base]   <= w_data[7:0];
                    mem[base+1] <= w_data[15:8];
                    mem[base+2] <= w_data[23:16];
                    mem[base+3] <= w_data[31:24];
                end
                default: ;   // width 2'b11 is never generated by control.v
            endcase
        end
    end

    // Sign extension on loads is selected by funct3[2]; stores ignore is_signed.
    always @(*) begin
        case (width)
            `MEM_B: r_data = is_signed ? {{24{mem[base][7]}},   mem[base]}
                                       : {24'h0,                mem[base]};
            `MEM_H: r_data = is_signed ? {{16{mem[base+1][7]}}, mem[base+1], mem[base]}
                                       : {16'h0,                mem[base+1], mem[base]};
            `MEM_W: r_data = {mem[base+3], mem[base+2], mem[base+1], mem[base]};
            default: r_data = 32'h0;
        endcase
    end

    // synthesis translate_off
    integer i;
    initial begin
        for (i = 0; i < 4096; i = i + 1) begin
            mem[i] = 8'h0;
        end
    end
    // synthesis translate_on
endmodule
